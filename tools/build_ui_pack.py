#!/usr/bin/env python3
"""Embed the web UI (data/*) into the firmware image as a generated header.

The INTEGRATED build used to serve the web UI from the SPIFFS partition at
0x330000, which made "the firmware" two separate flash images: the web OTA
endpoint could only update the app slot, so the UI silently stayed stale
after every OTA (and the partition was 100% full, so nothing else fit).
Embedding the three UI files in the app image makes OTA a single atomic
update — app and UI change together, and the existing rollback slot
protects both at once.

Run automatically by PlatformIO (extra_scripts, pre:) for every env; the
V2.x targets compile web_server.cpp too, so the header must always exist.
Output: src/web/generated/ui_pack.h (gitignored, never hand-edited).
"""
import hashlib
import os
import sys

# SCons exec()s pre: scripts without __file__ in scope, so under PlatformIO
# the repo root comes from the build environment's project dir; standalone
# (python3 tools/build_ui_pack.py) falls back to __file__.
try:
    from SCons.Script import Import
    Import("env")
    REPO = env.Dir(".").abspath
except Exception:
    REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(REPO, "data")
OUT = os.path.join(REPO, "src", "web", "generated", "ui_pack.h")

# (path under data/, URL name served, MIME type)
FILES = [
    ("index.html", "index.html", "text/html"),
    ("style.css", "style.css", "text/css"),
    ("app.js", "app.js", "application/javascript"),
]


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    blobs = []
    for path, url, mime in FILES:
        with open(os.path.join(DATA, path), "rb") as f:
            data = f.read()
        if not data:
            sys.exit(f"build_ui_pack: {path} is empty")
        sha = hashlib.sha256(data).hexdigest()[:8]
        var = f"k{url.replace('.', '_')}"
        lines = [f"static const uint8_t {var}[] PROGMEM = {{"]
        hexs = data.hex()
        lines.append(", ".join("0x" + hexs[i:i + 2] for i in range(0, len(hexs), 32)))
        lines.append("};")
        blobs.append((var, url, mime, len(data), sha, lines))

    out = []
    out.append("// AUTO-GENERATED by tools/build_ui_pack.py — DO NOT EDIT.")
    out.append("// Source of truth: data/index.html, data/style.css, data/app.js.")
    out.append("// Re-runs on every build (PlatformIO pre: script).")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("namespace uipack {")
    out.append("")
    out.append("struct Entry {")
    out.append("    const char* name;      // URL path (no leading slash)")
    out.append("    const char* mime;")
    out.append("    uint32_t size;")
    out.append("    const uint8_t* data;")
    out.append("};")
    out.append("")
    for var, url, mime, size, sha, lines in blobs:
        out += lines
        out.append(f"// {url}: {size} bytes, sha256:{sha}")
        out.append("")
    out.append("static const Entry kEntries[] PROGMEM = {")
    for var, url, mime, size, sha, _ in blobs:
        out.append(f'    {{ "{url}", "{mime}", {size}u, {var} }},')
    out.append("};")
    out.append("")
    out.append(f"static const unsigned kCount = {len(blobs)}u;")
    out.append("} // namespace uipack")
    out.append("")

    content = "\n".join(out)
    old = ""
    if os.path.exists(OUT):
        with open(OUT) as f:
            old = f.read()
    if old != content:
        with open(OUT, "w") as f:
            f.write(content)
        print(f"build_ui_pack: wrote {os.path.relpath(OUT, REPO)} ({len(content)} bytes)")
    else:
        print(f"build_ui_pack: {os.path.relpath(OUT, REPO)} up to date")


if __name__ == "__main__":
    main()
